export function evaluateCaloricCOWS({
  caloricTemp = 'cold',    // 'cold' | 'warm'
  caloricSide = 'right',   // 'right' | 'left' (patient's ear)
  conscious = false,       // true (awake cortex -> fast corrective nystagmus) | false (coma -> tonic only!)
  brainstemIntact = true   // true (VOR intact) | false (brainstem dead -> no eye movement)
} = {}) {
  if (!brainstemIntact) {
    return {
      tonicDirection: 'none',
      fastNystagmus: 'none',
      eyeShiftX: 0,
      headline: 'بدون هرگونه حرکت چشمی (فقدان کامل VOR)',
      clinicalMeaning: 'چشم‌ها در خط وسط ثابت می‌مانند: نشانه آسیب شدید ساقه مغز (پونز/وستیبولار — یکی از معیارهای کلیدی ارزیابی مرگ مغزی، پس از اطمینان از سلامت پرده صماخ و نبود سرومن/مسدودکننده).',
      badge: 'badge-rose'
    };
  }

  // Cold water inhibits ipsilateral labyrinth -> unopposed contralateral labyrinth pushes eyes TONICALLY toward the irrigated (cold) ear.
  // Warm water stimulates ipsilateral labyrinth -> eyes deviate TONICALLY away from the irrigated (warm) ear.
  const tonicToward = caloricTemp === 'cold'
    ? caloricSide
    : (caloricSide === 'right' ? 'left' : 'right');

  // Fast corrective phase (named direction of nystagmus) is generated by intact frontal cortex OPPOSITE to tonic drift (COWS: Cold Opposite, Warm Same)
  const fastToward = tonicToward === 'right' ? 'left' : 'right';

  // In examiner front view: patient's right is viewer's LEFT (-x), patient's left is viewer's RIGHT (+x)
  const eyeShiftX = tonicToward === 'right' ? -11 : 11;
  const earFa = caloricSide === 'right' ? 'راست' : 'چپ';
  const tonicFa = tonicToward === 'right' ? 'راست' : 'چپ';
  const fastFa = fastToward === 'right' ? 'راست' : 'چپ';

  if (conscious) {
    return {
      tonicDirection: tonicToward,
      fastNystagmus: fastToward,
      eyeShiftX,
      headline: `نیستاگموس فعال به سمت ${fastFa} (قانون COWS — کورتکس و ساقه هر دو سالم!)`,
      clinicalMeaning: `در فرد هوشیار یا کمای سایکوژنیک، تزریق آب ${caloricTemp === 'cold' ? 'سرد' : 'گرم'} در گوش ${earFa} ابتدا رانش آهسته به ${tonicFa} و بلافاصله نیستاگموس سریع اصلاحی به سمت ${fastFa} ایجاد می‌کند (کورتکس فرونتال بیدار است!).`,
      badge: 'badge-emerald'
    };
  }

  return {
    tonicDirection: tonicToward,
    fastNystagmus: 'absent',
    eyeShiftX,
    headline: `انحراف تونیک پایدار به سمت ${tonicFa} بدون نیستاگموس (کمای واقعی با ساقه مغز سالم)`,
    clinicalMeaning: `تزریق آب ${caloricTemp === 'cold' ? 'سرد' : 'گرم'} در گوش ${earFa} باعث انحراف تونیک چشم‌ها به سمت ${tonicFa} می‌شود، اما به دلیل اختلال قشر مغز در کمای واقعی، فاز سریع اصلاحی (نیستاگموس) حذف شده است. ساقه مغز (CN VIII → هسته دهلیزی → PPRF/MLF → CN VI/III) سالم است.`,
    badge: 'badge-cyan'
  };
}

export function recommendMeningitisEmpiric({
  ageGroup = 'adult-18-50',       // 'neonate' | 'child-1m-18' | 'adult-18-50' | 'older-50'
  immunocompromised = false,
  postNeurosurgeryOrShunt = false,
  severeBetaLactamAllergy = false
} = {}) {
  const needsListeria = ageGroup === 'neonate' || ageGroup === 'older-50' || immunocompromised;
  const regimens = [];
  const pathogens = [];
  let dexamethasone = 'دگزامتازون ۱۰ میلی‌گرم IV (۰.۱۵ mg/kg در اطفال) ۱۵–۲۰ دقیقه پیش از اولین دوز آنتی‌بیوتیک یا هم‌زمان با آن (به‌ویژه در پنوموکوک، هر ۶ ساعت تا ۴ روز).';

  if (postNeurosurgeryOrShunt) {
    pathogens.push('Staphylococcus aureus (شامل MRSA)', 'Coagulase-negative Staphylococci', 'Pseudomonas aeruginosa و باسیل‌های گرم‌منفی بیمارستانی');
    regimens.push('وانکومایسین ۱۵–۲۰ mg/kg IV هر ۸–۱۲ ساعت (هدف AUC/MIC یا تراف ۱۵–۲۰)');
    regimens.push(severeBetaLactamAllergy
      ? 'آزترئونام ۲ گرم IV هر ۶–۸ ساعت (یا سیپروفلوکساسین ۴۰۰mg IV هر ۸ ساعت) برای پوشش پسودوموناس'
      : 'سفپیم ۲ گرم IV هر ۸ ساعت (یا سفتازیدیم ۲ گرم IV هر ۸ ساعت، یا مروپنم ۲ گرم IV هر ۸ ساعت)');
    dexamethasone = 'در مننژیت پس از جراحی اعصاب/شنت، اندیکاسیون روتین دگزامتازون اثبات نشده است (تمرکز بر پوشش MRSA + Pseudomonas و خروج شنت عفونی).';
  } else if (ageGroup === 'neonate') {
    pathogens.push('Group B Streptococcus (GBS)', 'E. coli و گرم‌منفی‌های روده‌ای', 'Listeria monocytogenes');
    regimens.push('آمپی‌سیلین (دوز مننژیتی نوزاد) + سفوتاکسیم (یا جنتامایسین؛ از سفتریاکسون در نوزادان به دلیل جابه‌جایی بیلی‌روبین و کرن‌ایکتروس پرهیز کنید!)');
    dexamethasone = 'در نوزادان زیر ۶ هفته دگزامتازون توصیه نمی‌شود.';
  } else {
    pathogens.push('Streptococcus pneumoniae (شایع‌ترین)', 'Neisseria meningitidis');
    if (ageGroup === 'child-1m-18') pathogens.push('Haemophilus influenzae (در واکسینه‌نشده‌ها)');
    if (needsListeria) pathogens.push('Listeria monocytogenes (الزام پوشش آمپی‌سیلین!)');
    if (immunocompromised) pathogens.push('باسیل‌های گرم‌منفی هوازی از جمله Pseudomonas (بسته به شدت نقص ایمنی)');

    regimens.push('وانکومایسین ۱۵–۲۰ mg/kg IV هر ۸–۱۲ ساعت (پوشش پنوموکوک مقاوم به پنی‌سیلین/سفالوسپورین)');
    if (severeBetaLactamAllergy) {
      regimens.push('موکسی‌فلوکساسین ۴۰۰mg IV روزانه (یا کلرامفنیکل) + تری‌متوپریم-سولفامتوکسازول (TMP-SMX) در صورت نیاز به پوشش لیستریا');
    } else if (immunocompromised) {
      regimens.push('سفپیم ۲ گرم IV هر ۸ ساعت (یا مروپنم ۲ گرم IV هر ۸ ساعت) — پوشش هم‌زمان گرم‌منفی‌های مقاوم و پسودوموناس');
    } else {
      regimens.push('سفتریاکسون ۲ گرم IV هر ۱۲ ساعت (دوز مننژیتی دو برابر!) یا سفوتاکسیم ۲ گرم IV هر ۴–۶ ساعت');
    }

    if (needsListeria && !severeBetaLactamAllergy) {
      regimens.push('آمپی‌سیلین ۲ گرم IV هر ۴ ساعت (حیاتی برای پوشش Listeria monocytogenes — سفالوسپورین‌ها روی لیستریا بی‌اثرند!)');
    }
  }

  return {
    regimens,
    pathogens,
    dexamethasone,
    needsListeria,
    ctBeforeLpRule: 'فقط در صورت وجود نقص ایمنی، سابقه بیماری CNS، تشنج جدید (<۱ هفته)، پاپیل‌ادم، کاهش هوشیاری یا نقص عصبی کانونی قبل از LP سی‌تی مغز بگیرید — اما آنتی‌بیوتیک و دگزامتازون را هرگز به‌خاطر CT یا LP به تأخیر نیندازید (ابتدا کشت خون ← دگزامتازون + آنتی‌بیوتیک ← CT ← LP)!'
  };
}

