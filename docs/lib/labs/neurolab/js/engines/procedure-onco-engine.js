export function evaluateLpSafety({
  platelets = 180,          // x10^3 / uL
  inr = 1.1,
  anticoagulant = 'none',   // 'none' | 'aspirin' | 'clopidogrel' | 'lmwh-proph' | 'lmwh-tx' | 'doac'
  focalDeficitOrPapilledema = false,
  immunocompromisedOrCnsHx = false,
  newSeizureOrLowGcs = false,
  localSkinInfection = false
} = {}) {
  const blockers = [];
  const warnings = [];
  let ctBeforeLp = false;

  if (localSkinInfection) blockers.push('عفونت پوستی یا آبسه در محل ورود سوزن کمری (ممنوعیت مطلق LP به دلیل خطر ورود عفونت به مننژ!).');
  if (platelets < 50) blockers.push(`پلاکت بسیار پایین (${platelets}k < 50k/µL): خطر بالای هماتوم اپیدورال نخاعی — نیازمند تزریق پلاکت پیش از LP!`);
  else if (platelets < 100) warnings.push(`پلاکت بین ۵۰ تا ۱۰۰ هزار (${platelets}k): در نبود اختلال انعقادی دیگر معمولاً قابل‌انجام است اما احتیاط و اپراتور مجرب توصیه می‌شود.`);
  if (inr > 1.4) blockers.push(`اختلال انعقادی (INR = ${inr} > 1.4): پیش از LP با ویتامین K / PCC یا FFP اصلاح شود!`);

  if (anticoagulant === 'clopidogrel') blockers.push('کلوپیدوگرل (پلاویکس): بر اساس ASRA نیازمند قطع ۵ تا ۷ روز پیش از LP است (در اورژانس حیاتی مننژیت، با ارزیابی ریسک-منفعت/تجویز آنتی‌بیوتیک فوری بدون تأخیر).');
  else if (anticoagulant === 'lmwh-proph') blockers.push('انوکساپارین پروفیلاکسی: حداقل ۱۲ ساعت فاصله از آخرین دوز پیش از LP الزامی است!');
  else if (anticoagulant === 'lmwh-tx') blockers.push('انوکساپارین دوز درمانی: حداقل ۲۴ ساعت فاصله از آخرین دوز پیش از LP الزامی است!');
  else if (anticoagulant === 'doac') blockers.push('داروهای DOAC (آپیکسابان/ریواروکسابان/دابیگاتران): حداقل ۴۸ تا ۷۲ ساعت فاصله (یا ریورسال/تست اختصاصی) پیش از LP الزامی است!');
  else if (anticoagulant === 'aspirin') warnings.push('آسپرین (یا NSAID) به‌تنهایی «ممنوعیت LP نیست» و نیازی به قطع آن پیش از پروسیجر وجود ندارد!');

  if (focalDeficitOrPapilledema || immunocompromisedOrCnsHx || newSeizureOrLowGcs) {
    ctBeforeLp = true;
    warnings.push('اندیکاسیون قطعی CT مغز پیش از LP برقرار است (رد اثر فشاری و خطر فتق تونسیلار) — در شک به مننژیت، کشت خون + دگزامتازون + آنتی‌بیوتیک را پیش از CT شروع کنید!');
  }

  return {
    safeToProceedNow: blockers.length === 0 && !ctBeforeLp,
    ctBeforeLp,
    blockers,
    warnings,
    badge: blockers.length > 0 ? 'badge-rose' : (ctBeforeLp ? 'badge-amber' : 'badge-emerald'),
    headline: blockers.length > 0
      ? 'توقف! ممنوعیت / ریسک بالای هماتوم نخاعی یا عفونت'
      : (ctBeforeLp ? 'ابتدا CT مغز انجام دهید (اما آنتی‌بیوتیک را به تأخیر نیندازید!)' : 'شرایط بالینی و انعقادی برای انجام ایمن LP مناسب است')
  };
}

