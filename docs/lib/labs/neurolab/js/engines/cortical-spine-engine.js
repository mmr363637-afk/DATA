export function evaluateAphasia({ fluent = false, comprehension = true, repetition = false } = {}) {
  if (!fluent && comprehension && !repetition) return APHASIA_PROFILES.broca;
  if (fluent && !comprehension && !repetition) return APHASIA_PROFILES.wernicke;
  if (!fluent && !comprehension && !repetition) return APHASIA_PROFILES.global;
  if (fluent && comprehension && !repetition) return APHASIA_PROFILES.conduction;
  if (!fluent && comprehension && repetition) return APHASIA_PROFILES.transcorticalMotor;
  if (fluent && !comprehension && repetition) return APHASIA_PROFILES.transcorticalSensory;
  if (!fluent && !comprehension && repetition) return APHASIA_PROFILES.mixedTranscortical;
  return APHASIA_PROFILES.anomic;
}

