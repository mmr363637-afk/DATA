export function evaluateCaudaVsConus({
  saddleAnesthesia = false,
  urinaryRetention = false,
  reducedAnalTone = false,
  bilateralSymmetric = false,
  severeRadicularPain = false,
  babinskiOrHyperreflexia = false,
  feverOrIvduOrCancer = false
} = {}) {
  const redFlagCount = [saddleAnesthesia, urinaryRetention, reducedAnalTone].filter(Boolean).length;
  const urgentSurgery = redFlagCount >= 1;

  let localization = 'رادیکولوپاتی کمری بدون شواهد فشردگی حاد دم اسب/مخروط';
  let badge = 'badge-emerald';

  if (urgentSurgery && babinskiOrHyperreflexia) {
    localization = 'سندرم مخروط نخاعی (Conus Medullaris — سطح L1–L2): ترکیب علائم UMN (بابینسکی) + LMN همراه با درگیری زودرس اسفنکتر و بی‌حسی زینی متقارن';
    badge = 'badge-rose';
  } else if (urgentSurgery && bilateralSymmetric && !severeRadicularPain) {
    localization = 'احتمال بالای سندرم مخروط نخاعی (Conus Medullaris): شروع ناگهانی، متقارن، بی‌حسی زینی زودرس و درد رادیکولار کمتر';
    badge = 'badge-rose';
  } else if (urgentSurgery) {
    localization = 'اورژانس جراحی: سندرم دم اسب (Cauda Equina Syndrome — ریشه‌های L2–S5): ضایعه خالص LMN (آرفلکسی/فلج شل)، درد رادیکولار شدید و اختلال اسفنکتر/بی‌حسی زینی';
    badge = 'badge-rose';
  }

  const actions = [];
  if (urgentSurgery) {
    actions.push('MRI اورژانسی کل ستون فقرات کمری-ساکرال (و در صورت شک به مخروط، توراسیک تحتانی) بدون تأخیر!');
    actions.push('سوندگذاری مثانه (ثبت حجم باقیمانده PVR؛ بالای ۲۰۰mL بسیار هشداردهنده است) و مشاوره فوری جراحی اعصاب برای دکمپرشن ظرف <۲۴–۴۸ ساعت.');
  } else {
    actions.push('درمان محافظه‌کارانه، کنترل درد و آموزش علائم هشدار (بی‌حسی زینی، بی‌اختیاری یا احتباس ادرار، پیشرفت افتادگی پا) برای مراجعه فوری.');
  }
  if (feverOrIvduOrCancer) {
    actions.push('هشدار ویژه: MRI حتماً «با تزریق گادولینیوم (With Contrast)» درخواست شود تا آبسه اپیدورال نخاعی (SEA) یا متاستاز استخوانی/اپیدورال رد شود (در آبسه اپیدورال: آنتی‌بیوتیک وسیع‌الطیف IV شامل وانکومایسین + سفپیم/مروپنم پس از کشت خون)!');
  }

  return {
    urgentSurgery,
    redFlagCount,
    localization,
    badge,
    actions
  };
}

