export function buildNeuroConsultNote(data) {
  const ageSex = data.ageSex || 'بیمار ۶۵ ساله آقا';
  const cc = data.chiefComplaint || 'ضعف ناگهانی سمت راست بدن و اختلال تکلم';
  const lkw = data.lkw || '۹۰ دقیقه پیش (شاهددار)';
  const vitals = data.vitals || 'BP 168/92 | HR 86 | SpO2 97% | BS 118 mg/dL | GCS 14 (E4V4M6)';
  const exam = data.exam || 'NIHSS = 12؛ آفازی اکسپرسیو، انحراف نگاه به چپ، فلج مرکزی فاسیال راست، همی‌پارزی راست (دست ۱/۵، پا ۳/۵)، بابینسکی راست مثبت.';
  const loc = data.localization || 'قشر و مسیر قشری-نخاعی نیمکره چپ در قلمرو شریان مغزی میانی (Left MCA — شک به انسداد M1)';
  const ddx = data.ddx || '۱) سکته ایسکمیک حاد LVO چپ (ارجح)، ۲) خونریزی داخل مغزی چپ، ۳) فلج تاد پس از تشنج';
  const plan = data.plan || '۱) NCCT + CTA مغز و گردن اورژانس، ۲) چک کامل معیارهای آلتپلاز/تنکتپلاز و حفظ BP<185/110، ۳) آماده‌باش تیم نورواینترونشن برای EVT، ۴) NPO تا غربالگری بلع و مانیتورینگ Neuro-ICU.';

  return [
    '=== یادداشت مشاوره ساختارمند نورولوژی (NeuroLab SBAR Consult) ===',
    `بیمار / شکایت اصلی: ${ageSex} — ${cc}`,
    `زمان آخرین وضعیت طبیعی (LKW / سیر زمانی): ${lkw}`,
    `علائم حیاتی و قند خون: ${vitals}`,
    `معاینه عصبی کلیدی: ${exam}`,
    `لوکالیزاسیون آناتومیک: ${loc}`,
    `تشخیص‌های افتراقی (مرتب‌شده): ${ddx}`,
    `اقدامات فوری و پلن (Plan): ${plan}`
  ].join('\n');
}
