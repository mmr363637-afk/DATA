/**
 * SNOOP10 Secondary Headache Red-Flag & Primary ICHD-3 Classifier
 */
export function evaluateHeadache(input) {
  const redFlags = [];
  if (input.systemicFeverImmuno) redFlags.push('S: علائم سیستمیک (تب، کاهش وزن، نقص ایمنی/HIV یا سرطان فعال ← رد مننژیت/آبسه/متاستاز)');
  if (input.neuroDeficitPapilledema) redFlags.push('N: نقص عصبی کانونی، کاهش هوشیاری یا ادم پاپی (نیاز فوری به CT/MRI مغز)');
  if (input.thunderclap) redFlags.push('O: شروع ناگهانی رعدآسا (< ۱ دقیقه تا اوج — SAH / RCVS / CVT / آپوپلکسی هیپوفیز!)');
  if (input.olderThan50) redFlags.push('O: شروع جدید پس از سن ۵۰ سالگی (رد آرتریت سلول ژانت GCA با ESR/CRP و تومور مغزی!)');
  if (input.positionalOrValsalva) redFlags.push('P: تشدید با سرفه/والسالوا یا تغییر وضعیت (افزایش ICP / کیاری یا نشت CSF / هیپوتانسیون داخل جمجمه)');
  if (input.pregnancyPostpartum) redFlags.push('P: بارداری یا دوره پس از زایمان (رد پره‌اکلامپسی/PRES، ترومبوز سینوس وریدی CVT و RCVS!)');

  if (redFlags.length > 0) {
    return {
      isSecondaryRedFlag: true,
      redFlags,
      diagnosis: 'هشدار قرمز SNOOP10 فعال است — سردرد ثانویه خطرناک باید پیش از هر تشخیص اولیه رد شود!',
      badgeClass: 'badge-rose',
      acuteTx: 'انجام فوری تصویربرداری مغز (NCCT/MRI + در صورت لزوم CTV/MRV یا MRA) و در صورت شک به مننژیت/SAH یا سن >۵۰ سال، بررسی LP و ESR/CRP پیش از برچسب سردرد اولیه.',
      preventiveTx: 'درمان علت زمینه‌ای (مثلاً کورتون فوری پیش از بیوپسی شریان تمپورال در شک به GCA برای نجات بینایی!).'
    };
  }

  const pattern = input.pattern || 'migraine';
  if (pattern === 'cluster') {
    return {
      isSecondaryRedFlag: false,
      redFlags: [],
      diagnosis: 'سردرد خوشه‌ای (Cluster Headache — ICHD-3 TAC)',
      badgeClass: 'badge-amber',
      acuteTx: 'خط اول حاد: اکسیژن ۱۰۰٪ با جریان ۱۲–۱۵ لیتر/دقیقه با ماسک بدون تنفس مجدد (۱۵ دقیقه) + سوماتریپتان زیرجلدی ۶mg یا اسپری بینی زولمیتریپتان.',
      preventiveTx: 'پیشگیری خط اول: وراپامیل (با پایش ECG برای بلوک PR) + دوره کوتاه پل استروئید (پردنیزولون) در آغاز خوشه؛ نکته: بیمار برخلاف میگرن بی‌قرار است و در اتاق راه می‌رود!'
    };
  }
  if (pattern === 'tn') {
    return {
      isSecondaryRedFlag: false,
      redFlags: [],
      diagnosis: 'نورالژی تری‌ژمینال کلاسیک (Trigeminal Neuralgia — V2/V3)',
      badgeClass: 'badge-cyan',
      acuteTx: 'دردهای برق‌آسا و شوکی چندثانیه‌ای تحریک‌شده با لمس/مسواک/باد؛ در بحران حاد: فوسفنیتوئین یا لیدوکائین IV.',
      preventiveTx: 'درمان خط اول طلایی: کاربامازپین یا اکس‌کاربازپین (با چک سدیم سرم و HLA-B*1502 در نژادهای پرخطر). نکته قرمز: اگر سن <۴۰ سال یا دوطرفه یا همراه با بی‌حسی صورت بود ← MRI با گادولینیوم برای رد MS یا تومور CPA!'
    };
  }
  if (pattern === 'tension') {
    return {
      isSecondaryRedFlag: false,
      redFlags: [],
      diagnosis: 'سردرد تنشی (Tension-Type Headache — ICHD-3)',
      badgeClass: 'badge-emerald',
      acuteTx: 'دوطرفه، فشاری/باندمانند، خفیف تا متوسط، بدون تهوع و بدون تشدید با فعالیت فیزیکی: NSAIDs یا استامینوفن (محدود به < ۱۰–۱۵ روز/ماه برای پیشگیری از MOH).',
      preventiveTx: 'در فرم مزمن: آمی‌تریپتیلین با دوز پایین شبانه + مدیریت استرس و فیزیوتراپی عضلات گردن.'
    };
  }
  return {
    isSecondaryRedFlag: false,
    redFlags: [],
    diagnosis: 'سردرد میگرنی (Migraine — ICHD-3)',
    badgeClass: 'badge-accent',
    acuteTx: 'حملات ۴–۷۲ ساعته، یک‌طرفه/ضربان‌دار با تهوع یا فوتوفوبی/فونوفوبی: NSAIDs، تریپتان‌ها (در بیماران بدون بیماری عروق کرونر/سکته) یا جپنت‌ها (Rimegepant/Ubrogepant)؛ در اورژانس: متوکلوپرامید/پروکلرپرازین IV + کترولاک + منیزیم سولفات (از اپیوئیدها پرهیز کنید!).',
    preventiveTx: 'در ≥ ۴ روز سردرد ماهانه: پروپرانولول، توپیرامات، آمی‌تریپتیلین، والپروات (ممنوع در بارداری!) یا آنتی‌بادی‌های CGRP (ارنوماب/فرمانزوماب/گالکانزوماب).'
  };
}

