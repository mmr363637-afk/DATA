export function evaluateHardPacsSubmission(caseObj, studyObj, { pin, pickedDxId, pickedMgmtId }) {
  const dxCorrect = caseObj.dxOptions.some((o) => o.id === pickedDxId && o.correct);
  const mgmtCorrect = caseObj.mgmtOptions.some((o) => o.id === pickedMgmtId && o.correct);
  const pinRes = pin && studyObj?.roi ? evaluatePinAccuracy(pin, studyObj.roi) : { hit: false, dist: 999 };

  const pinPts = pinRes.hit ? 30 : (pin && pinRes.dist <= 28 ? 15 : 0);
  const dxPts = dxCorrect ? 40 : 0;
  const mgmtPts = mgmtCorrect ? 30 : 0;
  const totalScore = pinPts + dxPts + mgmtPts;

  let tier = 'نیاز به مرور دقیق تله رادیولوژی';
  if (totalScore >= 90) tier = 'استاد نورورادیولوژی (پین + تشخیص + اقدام کامل!)';
  else if (totalScore >= 70) tier = 'فلوشیپ نورورادیولوژی (عملکرد بالینی بسیار خوب)';
  else if (totalScore >= 40) tier = 'دستیار ارشد (بخش کلیدی درست، تله را مرور کنید)';

  return {
    totalScore,
    pinPts,
    dxPts,
    mgmtPts,
    pinHit: pinRes.hit,
    pinDist: pinRes.dist,
    dxCorrect,
    mgmtCorrect,
    passed: totalScore >= 70,
    tier,
    correctDxLabel: caseObj.dxOptions.find((o) => o.correct)?.label || '',
    correctMgmtLabel: caseObj.mgmtOptions.find((o) => o.correct)?.label || ''
  };
}

