export function evaluateOnCallShift(shift, answersMap, studiesById) {
  let totalPts = 0;
  let maxPts = 0;
  let criticalTotal = 0;
  let criticalCaught = 0;
  let criticalMisses = 0;
  let benignTotal = 0;
  let overcalls = 0;
  const breakdown = [];

  for (const c of shift.cases) {
    const ans = answersMap[c.id] || {};
    const study = studiesById[c.studyId];
    maxPts += 100;

    const triageExact = ans.triage === c.expectedTriage;
    const dxOk = c.options.some((o) => o.id === ans.dxId && o.correct);

    let pinOk = true;
    let pinPts = 20;
    if (c.needsPin) {
      const p = ans.pin && study?.roi ? evaluatePinAccuracy(ans.pin, study.roi) : { hit: false, dist: 999 };
      pinOk = p.hit;
      pinPts = p.hit ? 20 : (ans.pin && p.dist <= 28 ? 10 : 0);
    }

    const triagePts = triageExact ? 40 : (c.expectedTriage === 'URGENT' && ans.triage === 'STAT' ? 25 : 0);
    const dxPts = dxOk ? 40 : 0;
    const caseScore = triagePts + dxPts + pinPts;
    totalPts += caseScore;

    let criticalMissed = false;
    let overcalled = false;
    if (c.expectedTriage === 'STAT') {
      criticalTotal++;
      if (ans.triage === 'STAT' && dxOk) criticalCaught++;
      else {
        criticalMisses++;
        criticalMissed = true;
      }
    }
    if (c.expectedTriage === 'BENIGN') {
      benignTotal++;
      if (ans.triage && ans.triage !== 'BENIGN') {
        overcalls++;
        overcalled = true;
      }
    }

    breakdown.push({
      caseId: c.id,
      patient: c.patient,
      expectedTriage: c.expectedTriage,
      pickedTriage: ans.triage || '—',
      triageExact,
      dxOk,
      pinOk,
      caseScore,
      criticalMissed,
      overcalled,
      correctDx: c.options.find((o) => o.correct)?.label || '',
      pearls: c.pearls
    });
  }

  const pct = maxPts ? Math.round((totalPts / maxPts) * 100) : 0;
  const shiftPassed = pct >= 70 && criticalMisses === 0;
  let verdict = '⚠️ هشدار کشیک: خطای بحرانی STAT رخ داده — مرور فوری لازم است!';
  if (shiftPassed && overcalls === 0) verdict = '🏆 اتندینگ کشیک شب! صفر خطای STAT + صفر مثبت کاذب (Overcall)!';
  else if (shiftPassed) verdict = '✅ قبولی ایمن کشیک! همه موارد مرگبار STAT شکار شدند (فقط مراقب Overcall روی نرمال‌ها باشید).';
  else if (criticalMisses === 0) verdict = 'نمره زیر ۷۰٪ ولی خوشبختانه هیچ مورد STAT از دست نرفت — مرور تشخیص‌ها توصیه می‌شود.';

  return {
    pct,
    shiftPassed,
    verdict,
    criticalTotal,
    criticalCaught,
    criticalMisses,
    benignTotal,
    overcalls,
    breakdown
  };
}
