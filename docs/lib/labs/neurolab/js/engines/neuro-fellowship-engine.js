/* =========================================================================
   1. TIERED ICP / MONRO-KELLIE & HYPEROSMOLAR THERAPY ENGINE (BTF 4th Ed.)
   ========================================================================= */
export function evaluateIcpProtocol({
  icp = 26,
  map = 82,
  serumNa = 142,
  serumOsm = 295,
  akiOrChf = false,
  hypotensive = false,
  massLesion = false
} = {}) {
  const cpp = Math.round(map - icp);
  let complianceZone = 'compensated';
  let zoneLabel = 'ناحیه جبرانی (Compensated — شیب ملایم منحنی مورو-کلی)';
  let badge = 'badge-emerald';

  if (icp >= 22) {
    complianceZone = 'decompensated';
    zoneLabel = 'ناحیه بحرانی دکمپانسه (ICP ≥ 22 mmHg — شیب عمودی منحنی مورو-کلی و خطر فتق!)';
    badge = 'badge-rose';
  } else if (icp >= 15) {
    complianceZone = 'knee';
    zoneLabel = 'نقطه زانویی منحنی (Borderline 15–21 mmHg — کاهش شدید ذخیره جبرانی CSF/وریدی)';
    badge = 'badge-amber';
  }

  // Hyperosmolar choice: Mannitol vs Hypertonic Saline (HTS 3% / 23.4%)
  let osmChoice = 'سالین هایپرتونیک (HTS 3% یا بولوس 23.4% از خط مرکزی) یا مانیتول 0.5–1 g/kg هر دو قابل‌استفاده‌اند.';
  let osmReason = 'سدیم سرم زیر ۱۵۵ و اسمولالیته زیر ۳۲۰ است و همودینامیک پایدار است.';
  if (hypotensive || akiOrChf) {
    osmChoice = 'ارجحیت قاطع: سالین هایپرتونیک (Hypertonic Saline 3% بولوس 250mL یا 23.4% 30mL از خط مرکزی) — از مانیتول پرهیز کنید!';
    osmReason = hypotensive
      ? 'بیمار هیپوتانسیو است: مانیتول با دیورز اسموتیک حجم داخل عروقی را کاهش داده و CPP را سقوط می‌دهد؛ HTS حجم و فشار خون را حفظ می‌کند!'
      : 'در نارسایی کلیه (AKI) یا نارسایی قلبی (CHF)، مانیتول تجمع یافته و خطر نکروز توبولی/ادم ریوی دارد.';
  } else if (serumNa >= 155) {
    osmChoice = 'هشدار سقف سدیم (Na ≥ 155–160 mEq/L): توقف افزایش HTS — در صورت اسمولالیته <320 و کلیه سالم، دوز محتاطانه مانیتول یا ارتقای پله درمانی!';
    osmReason = 'سدیم بالای ۱۶۰ خطر آسیب کلیوی، خونریزی ساب‌دورال و اختلالات همودینامیک دارد.';
  } else if (serumOsm >= 320) {
    osmChoice = 'هشدار سقف اسمولالیته (Osm ≥ 320 mOsm/kg): از دوز اضافی مانیتول خودداری کنید (خطر AKI و ریباند ICP)!';
    osmReason = 'اسمولالیته ≥۳۲۰ یا Osmolar Gap >20 نشانه تجمع مانیتول در خون است.';
  }

  const tiers = [
    {
      tier: 'پله ۰ (پایه Neuro-ICU)',
      items: [
        'بالابردن سر تخت ۳۰ درجه با خط وسط نگه داشتن گردن (تسهیل درناژ ورید ژوگولار)',
        'نرموترمی (دمای <37.5°C)، حفظ اکسیژن‌رسانی (SpO2 ≥94%) و نرموکاپنی (PaCO2 35–40)',
        `حفظ فشار پرفیوژن مغزی CPP در هدف ۶۰–۷۰ mmHg (مقدار فعلی شما: ${cpp} mmHg ${cpp < 60 ? '⚠ خطر ایسکمی!' : '✓ مناسب'})`,
        'پیشگیری تشنج (لوتیراستام در هفته اول TBI شدید) و پرهیز از هیپوناترمیک/محلول‌های هیپوتونیک'
      ]
    },
    {
      tier: 'پله ۱ (ICP پایدار ≥ 22 mmHg > 5 دقیقه)',
      items: [
        'درناژ متناوب CSF از طریق EVD (در صورت تعبیه بودن)',
        'آرام‌بخشی و ضددرد کافی (پروپوفول + فنتانیل) برای حذف تحریک/آژیتاسیون',
        osmChoice
      ]
    },
    {
      tier: 'پله ۲ (مقاوم به پله ۱)',
      items: [
        'هیپرونتیلاسیون کوتاه‌مدت کنترل‌شده فقط به‌عنوان پل نجات فتق حاد (PaCO2 32–35 mmHg — پرهیز از PaCO2 <30 و طولانی‌مدت به دلیل ایسکمی!)',
        'آزمون کوتاه شل‌کننده عضلانی (Cisatracurium) در صورت لرز/عدم هماهنگی با ونتیلاتور',
        'ارزیابی مجدد CT اورژانس برای رد هماتوم جدید یا هیدروسفالی قابل تخلیه جراحی'
      ]
    },
    {
      tier: 'پله ۳ (ICP سرکش / Refractory)',
      items: [
        massLesion
          ? 'کرانیوتومی/همی‌کرانیکتومی دکمپرسیو اورژانسی (به‌ویژه در ضایعه فضاگیر یا سکته بدخیم MCA!)'
          : 'همی‌کرانیکتومی دکمپرسیو دوطرفه/یک‌طرفه (کارآزمایی RESCUEicp)',
        'کمای باربیتوراتی (پنتوباربیتال تا الگوی Burst-Suppression در cEEG با پایش دقیق فشار خون)',
        'هیپوترمی درمانی هدفمند (۳۵–۳۶°C در موارد انتخابی سرکش)'
      ]
    }
  ];

  return {
    icp,
    map,
    cpp,
    cppAlert: cpp < 60,
    complianceZone,
    zoneLabel,
    badge,
    osmChoice,
    osmReason,
    tiers
  };
}

