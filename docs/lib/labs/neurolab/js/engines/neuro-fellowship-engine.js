export function evaluateHyperthermicToxidrome({
  spontaneousOrInducibleClonus = false,
  hyperreflexia = false,
  leadPipeRigidity = false,
  serotonergicExposure = false,
  antipsychoticOrDopamineStop = false,
  volatileAnestheticOrSuccinyl = false,
  dryFlushedSkinMydriasis = false,
  ckVeryHigh = false
} = {}) {
  // Hunter Serotonin Toxicity Criteria: serotonergic drug + (spontaneous clonus OR inducible/ocular clonus + agitation/diaphoresis OR tremor+hyperreflexia)
  if (volatileAnestheticOrSuccinyl && (leadPipeRigidity || ckVeryHigh)) {
    return {
      id: 'mh',
      badge: 'badge-rose',
      diagnosis: 'هیپرترمی بدخیم (Malignant Hyperthermia — جهش کانال RYR1)',
      mechanism: 'آزادسازی انفجاری کلسیم از شبکه سارکوپلاسمیک پس از سوکسینیل‌کولین یا گازهای بیهوشی (سووفلوران/هالوتان) ← افزایش برق‌آسای EtCO2، ریجیدیتی عضلانی، اسیدوز و تب >40°C.',
      antidote: 'قطع فوری عامل بیهوشی + تزریق اورژانسی **دانترولن (Dantrolene 2.5 mg/kg IV بولوس تکرارشونده)** + خنک‌سازی فعال + کنترل هیپرکالمی!'
    };
  }
  if (serotonergicExposure && (spontaneousOrInducibleClonus || hyperreflexia)) {
    return {
      id: 'serotonin',
      badge: 'badge-rose',
      diagnosis: 'سندرم سروتونین حاد (معیار Hunter مثبت! — شروع سریع <۲۴ ساعت)',
      mechanism: 'بیش‌تحریکی گیرنده‌های 5-HT2A/1A (مثلاً ترکیب SSRI/SNRI با لینزولید، ترامادول، MAOI، متیلن‌بلو یا دکسترومتورفان) ← «هیپراکستابیلیتی عصبی-عضلانی: کلونوس مچ پا/چشمی + هیپررفلکسی (بیشتر در پاها) + دیافورز/اسهال».',
      antidote: '۱) قطع فوری همه داروهای سروتونرژیک (از جمله لینزولید/ترامادول)، ۲) **بنزودیازپین‌ها (لورازپام/دیازپام IV)** پایه اصلی کنترل آژیتاسیون/کلونوس/تب، ۳) آنتاگونیست 5-HT2A: **سیپروهپتادین (Cyproheptadine ۱۲mg لودینگ سپس ۲mg q2h)** — از بروموکریپتین و هالوپریدول اکیداً پرهیز کنید!'
    };
  }
  if (antipsychoticOrDopamineStop && leadPipeRigidity) {
    return {
      id: 'nms',
      badge: 'badge-rose',
      diagnosis: 'سندرم نورولپتیک بدخیم (NMS — شروع تحت‌حاد طی ۱–۳ روز)',
      mechanism: 'بلوک شدید گیرنده D2 دوپامین (هالوپریدول، متوکلوپرامید، آنتی‌سایکوتیک‌ها یا قطع ناگهانی لوودوپا در پارکینسون!) ← «ریجیدیتی یکنواخت لوله‌سربی (Lead-Pipe)، برادیکینزی، هیپورفلکسی (برخلاف کلونوس سروتونین!)، تب بالا، ناپایداری اتونوم و CK بسیار بالا (>1000–10000)».',
      antidote: '۱) قطع فوری آنتی‌سایکوتیک (یا شروع مجدد فوری لوودوپا در پارکینسون!)، ۲) هیدراتاسیون تهاجمی (رابدومیولیز) + بنزودیازپین، ۳) **بروموکریپتین (آگونیست D2) و/یا دانترولن (شل‌کننده عضلانی)** در موارد متوسط تا شدید!'
    };
  }
  if (dryFlushedSkinMydriasis) {
    return {
      id: 'anticholinergic',
      badge: 'badge-amber',
      diagnosis: 'توکسیدروم آنتی‌کولینرژیک (آتروپین، TCA، دیفن‌هیدرامین، اسکوپولامین)',
      mechanism: 'بلوک گیرنده موسکارینی مرکزی و محیطی: «پوست خشک و برافروخته (برخلاف تعریق شدید سروتونین/NMS)، مردمک‌های گشاد، دلیریوم/توهم، احتباس ادرار، نبود صدای روده و بدون کلونوس یا ریجیدیتی».',
      antidote: 'مراقبت حمایتی + بنزودیازپین برای آژیتاسیون؛ در دلیریوم شدید بدون پهن‌شدن QRS (رد مسمومیت TCA!): **فیزوستیگمین** آهسته IV تحت پایش ECG.'
    };
  }
  return {
    id: 'undifferentiated',
    badge: 'badge-cyan',
    diagnosis: 'نیاز به تکمیل نشانه‌های بالینی و سابقه دارویی',
    mechanism: 'کلید طلایی افتراق کنار تخت: کلونوس + هیپررفلکسی (سروتونین) vs ریجیدیتی لوله‌سربی + هیپورفلکسی + CK بالا (NMS) vs پوست خشک + میدریازیس (آنتی‌کولینرژیک).',
    antidote: 'ابتدا معاینه دقیق رفلکس/کلونوس مچ پا، تون عضلانی، پوست (خشک vs خیس)، CK و لیست کامل داروها (به‌ویژه لینزولید، ترامادول، متوکلوپرامید و قطع لوودوپا).'
  };
}

