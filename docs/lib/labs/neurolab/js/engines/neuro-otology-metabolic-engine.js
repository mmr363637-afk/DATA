/* =========================================================================
   2. OBSTETRIC NEUROLOGY: ECLAMPSIA MgSO4 ENGINE & PREGNANCY NEURO-DRUGS
   ========================================================================= */
export function evaluateEclampsiaProtocol({
  bpSys = 166,
  bpDia = 108,
  activeSeizure = true,
  patellarReflexAbsent = false,
  respRate = 16,
  urineMlHr = 45,
  serumMgMeq = 4.8
} = {}) {
  const mgToxicity = patellarReflexAbsent || respRate < 12 || serumMgMeq >= 7.0;
  const severeHtn = bpSys >= 160 || bpDia >= 110;
  const oliguria = urineMlHr < 30;
  const alerts = [];

  if (mgToxicity) {
    alerts.push('مسمومیت خطرناک سولفات منیزیم! (از بین رفتن رفلکس پاتلار در Mg ~7–10 mEq/L، سپس تضعیف تنفس در >10–12 و ایست قلبی >15) ← **قطع فوری انفوزیون MgSO4 و تزریق آنتی‌دوت: کلسیم گلوکونات ۱ گرم (10mL محلول 10%) آهسته وریدی طی ۳–۵ دقیقه!**');
  }
  if (severeHtn) {
    alerts.push('هیپرتانسیون شدید بارداری (≥160/110 — خطر فوری خونریزی ICH و PRES!) ← کاهش کنترل‌شده فشار ظرف ۳۰–۶۰ دقیقه با **لابتالول IV، هیدرالازین IV یا نیفدیپین خوراکی کوتاه‌اثر** (هرگز ACEi/ARB/نیتروپروساید ندهید!).');
  }
  if (oliguria) {
    alerts.push('الیگوری (<30 mL/hr): چون دفع منیزیم ۱۰۰٪ کلیوی است، دوز نگهداری MgSO4 را کاهش/متوقف کرده و سطح سرمی Mg را هر ۴ ساعت چک کنید!');
  }

  return {
    mgToxicity,
    severeHtn,
    oliguria,
    badge: mgToxicity ? 'badge-rose' : (activeSeizure || severeHtn ? 'badge-amber' : 'badge-emerald'),
    primaryRegimen: activeSeizure
      ? 'خط اول قطعی (برتر از فنی‌توئین و دیازپام!): **سولفات منیزیم (MgSO4) ۴ تا ۶ گرم IV طی ۱۵–۲۰ دقیقه ← سپس نگهداری ۱ تا ۲ گرم در ساعت IV** (تا ۲۴ ساعت پس از زایمان یا آخرین تشنج). در تشنج راجعه حین Mg: بولوس اضافه ۲ گرم IV MgSO4 (فقط در صورت مقاومت شدید: بنزودیازپین/لوتیراستام). درمان قطعی نهایی: ختم بارداری پس از پایدارسازی مادر!'
      : 'پروفیلاکسی پره‌اکلامپسی با ویژگی‌های شدید: MgSO4 با پایش ساعتی رفلکس پاتلار، تعداد تنفس (≥12) و برون‌ده ادراری (≥30 mL/hr).',
    alerts
  };
}

